/* Admin page: skip, remove, pause requests, print the QR sign. */
(function () {
  'use strict';
  var J = window.Jukebox, C = J.C, DB = J.DB, h = J.h;
  var $ = function (id) { return document.getElementById(id); };
  var settings = {}, queue = [], timer = null, volTouchAt = 0, volTimer = null;

  J.banner($('demoBanner'));
  J.initMenu({ mount: $('menuMount'), current: 'admin' });

  function unlocked() { try { return sessionStorage.getItem('jb_admin') === '1'; } catch (e) { return false; } }
  function unlock() { try { sessionStorage.setItem('jb_admin', '1'); } catch (e) { } open(); }

  if (!String(C.adminPin || '').length || unlocked()) open(); else $('gate').hidden = false;
  $('gateForm').addEventListener('submit', function (e) {
    e.preventDefault();
    if ($('pin').value === String(C.adminPin)) unlock(); else $('gateErr').hidden = false;
  });

  function open() {
    $('gate').hidden = true; $('panel').hidden = false;
    $('signNames').textContent = C.coupleNames;
    var guestUrl = location.href.replace(/admin\.html.*$/, '');
    if (/^file:/.test(location.protocol)) guestUrl += 'index.html';
    $('guestUrl').value = guestUrl; drawQr();
    $('guestUrl').addEventListener('input', drawQr);
    refresh(); timer = setInterval(refresh, 4000);
  }

  function drawQr() {
    var url = $('guestUrl').value.trim(); $('signUrl').textContent = url;
    var box = $('qr'); box.textContent = '';
    if (!url) return;
    try {
      var qr = qrcode(0, 'M'); qr.addData(url); qr.make();
      box.innerHTML = qr.createSvgTag({ cellSize: 6, margin: 2, scalable: true });   // SVG generated by our own library, not user HTML
    } catch (e) { box.textContent = 'Could not draw the QR code.'; }
  }

  function row(i, n, isNext) {
    var kids = [h('div', { class: 'num' }, String(n)), J.thumb(i.art, i.title),
    h('div', { class: 'meta' }, [h('div', { class: 't' }, i.title), h('div', { class: 'a' }, i.artist)])];
    if (isNext !== null) {
      kids.push(h('button', { class: 'btn ghost mini', title: 'Play next', 'aria-label': 'Play next', onclick: function () { playFirst(i); } }, '↑'));
      kids.push(h('button', { class: 'btn danger mini', title: 'Remove', 'aria-label': 'Remove', onclick: function () { remove(i); } }, h('i', { class: 'fa-solid fa-xmark' })));
    } else if (!i.failed) {
     kids.push(h('button', { class: 'btn ghost mini', title: 'Play again', 'aria-label': 'Play again', onclick: function () { replay(i); } }, h('i', { class: 'fa-solid fa-rotate-right' })));
    }
    return h('li', { class: 'song' }, kids);
  }

  function fill(el, kids) { while (el.firstChild) el.removeChild(el.firstChild); kids.forEach(function (k) { el.appendChild(k); }); }

  function render() {
    var up = queue.filter(function (i) { return !i.played && !i.failed; });
    var done = queue.filter(function (i) { return i.played || i.failed; })
      .sort(function (a, b) { return (b.playedAt || b.order || 0) - (a.playedAt || a.order || 0); }).slice(0, 20);
    $('count').textContent = up.length ? String(up.length) : '';
    fill($('list'), up.length ? up.map(function (i, n) { return row(i, n + 1, false); }) : [h('li', {}, h('p', { class: 'msg' }, 'Nothing waiting.'))]);
    fill($('played'), done.length ? done.map(function (i, n) {
      var r = row(i, n + 1, null);
      if (i.failed) r.querySelector('.t').appendChild(h('span', { class: 'you' }, "couldn't play"));
      return r;
    }) : [h('li', {}, h('p', { class: 'msg' }, 'Nothing yet.'))]);
    var mins = Number(C.replayAfterMinutes);
    $('replayNote').textContent = 'Tap ↻ to put a song back in the queue. ' +
      (mins > 0 ? 'Guests can request it again after ' + mins + ' minutes.' : 'Guests cannot request a song twice.');
    $('np').textContent = settings.now && settings.now.title ? settings.now.title + ' – ' + (settings.now.artist || '') : '–';
   $('pauseBtn').innerHTML = settings.paused ? '<i class="fa-solid fa-play"></i> Resume guest requests' : '<i class="fa-solid fa-circle-pause"></i> Pause guest requests';
    $('musicBtn').innerHTML = settings.musicPaused ? '<i class="fa-solid fa-play"></i> Resume music' : '<i class="fa-solid fa-pause"></i> Pause music';
    $('volNote').hidden = settings.volumeOk !== false;
    $('vol').disabled = settings.volumeOk === false;
    // follow the volume set from another device, but not while this one is being dragged
    if (typeof settings.volume === 'number' && Date.now() - volTouchAt > 4000) {
      $('vol').value = Math.round(settings.volume); $('volLabel').textContent = Math.round(settings.volume) + '%';
    }
  }

  async function refresh() {
    try { var r = await Promise.all([DB.getQueue(), DB.getSettings()]); queue = r[0]; settings = r[1] || {}; render(); } catch (e) { }
  }

  async function remove(i) {
    try { await DB.remove(i.id); J.toast('Removed'); refresh(); } catch (e) { J.toast("Couldn't remove – try again"); }
  }
  /* put a song that already played back at the end of the queue (guests have to wait; you don't) */
  async function replay(i) {
    if (queue.some(function (x) { return x.key === i.key && !x.played && !x.failed; })) return J.toast('That song is already in the queue');
    var rec = { key: i.key, title: i.title, artist: i.artist, art: i.art || '', durationMs: i.durationMs || 0 };
    if (i.videoId) rec.videoId = i.videoId;
    try { await DB.add(rec); J.toast('Added to the end of the queue'); refresh(); } catch (e) { J.toast("Couldn't add it – try again"); }
  }
  async function playFirst(i) {
    var up = queue.filter(function (x) { return !x.played && !x.failed; });
    var min = up.length ? up[0].order : Date.now();
    try { await DB.update(i.id, { order: min - 1 }); J.toast('Moved to the front'); refresh(); } catch (e) { J.toast("Couldn't move it – try again"); }
  }

  $('skipBtn').onclick = async function () {
    try { await DB.setSettings({ skipToken: Date.now() }); J.toast('Skipping…'); } catch (e) { J.toast("Couldn't skip – try again"); }
  };
  $('pauseBtn').onclick = async function () {
    try { await DB.setSettings({ paused: !settings.paused }); refresh(); } catch (e) { J.toast('Try again'); }
  };
  $('musicBtn').onclick = async function () {
    try {
      var next = !settings.musicPaused;
      await DB.setSettings({ musicPaused: next });
      settings.musicPaused = next; render();
      J.toast(next ? 'Pausing the music…' : 'Resuming the music…');
    } catch (e) { J.toast("Couldn't reach the player – try again"); }
  };
  $('vol').addEventListener('input', function () {
    var v = Number(this.value); volTouchAt = Date.now();
    $('volLabel').textContent = v + '%';
    clearTimeout(volTimer);
    volTimer = setTimeout(function () {
      DB.setSettings({ volume: v }).then(function () { settings.volume = v; }).catch(function () { J.toast("Couldn't change the volume – try again"); });
    }, 300);
  });
  $('shuffleBtn').onclick = async function () {
    try {
      var n = await J.shuffleQueue();
      J.toast(n > 1 ? 'Shuffled ' + n + ' requests' : 'Need at least 2 requests to shuffle');
      refresh();
    } catch (e) { J.toast("Couldn't shuffle – try again"); }
  };
  $('printBtn').onclick = function () { window.print(); };
  $('resetBtn').onclick = async function () {
    if (!confirm('Delete every song from the queue and the history? This cannot be undone.')) return;
    try { await DB.clearQueue(); J.toast('Cleared'); refresh(); } catch (e) { J.toast('Try again'); }
  };
})();
